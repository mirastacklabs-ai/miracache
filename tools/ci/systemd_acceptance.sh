#!/usr/bin/env bash
# Product acceptance under systemd: install and run the real release build the way the benchmark runs it on bare metal
# (deploy/systemd/README.md), on ONE Linux host, as root, with systemd and soft-RDMA (rxe0, tools/dev/rdma_setup.sh).
#   sudo RAIL_NETDEV=eth1 tools/ci/systemd_acceptance.sh
# Env: RAIL_NETDEV (default eth0) = the netdev rxe0 sits on; MIRA_ACCEPT_SKIP_BUILD=1 reuses build/release;
#      MIRA_ACCEPT_REMOVE_USER=1 also deletes the `mira` user at the end; MIRA_ACCEPT_DEVICE (default rxe0);
#      MIRA_ACCEPT_APT=1 apt-installs missing runtime libraries (libibverbs1 librdmacm1t64 ibverbs-providers) and
#      removes them again at teardown (without it, missing libraries are a FAIL with the apt hint).
# 1. builds the release preset (mira-memnode, the e2e client test) and the Go controller + mirctl in the dev container;
# 2. creates the `mira` user (README command, idempotent), lab PKI (tools/dev/lab-certs.sh), installs binaries to
#    /usr/local/bin and configs/keys to /etc/miracache with the README's owners and modes;
# 3. bundle mode: a signing key (mirctl keys gen), three memory nodes as units generated from the shipped
#    mira-memnode.service, a first publish with mirctl, the controller hand-over (--recover-from), then the controller
#    unit generated from the shipped mira-controller.service;
# 4. acceptance checks, each printing PASS/FAIL (see check names below);
# 5. teardown always (trap): units, /etc/miracache, /usr/local/bin files, state dirs, mounts, temp PKI.
# Store: backing = "file" on a per-node tmpfs mount owned by mira (server.cpp: "use tmpfs or hugetlbfs"); the benchmark
# uses hugetlbfs with 1 GiB pages (runbook §3.2), which must be reserved at boot and is not done here.
# What the generated units change against the shipped ones (multi-instance on one host only):
#   memnode N:   unit mira-memnode-acc-N.service; StateDirectory=miracache-acc-N; --config /etc/miracache/memnode-N.toml
#   controller:  unit mira-controller-acc.service; StateDirectory=miracache-controller-acc (store + audit paths follow);
#                --api-listen 127.0.0.1:29470 instead of :9470
# Final line: "OK: systemd acceptance ..." or "FAIL: ...", exit status to match.
set -u  # no pipefail: "journalctl | grep -q" would fail on SIGPIPE
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$ROOT"
W=$ROOT/build/systemd-accept      # temp PKI and configs (inside the repo so the dev container sees the client cert)
B=$ROOT/build/release
N=3
RAIL0=27470 ADMIN0=29465 TEL0=29474 CTL_PORT=29470   # rails 27471-73, admin 29466-68, telemetry 29475-77
DEV=${MIRA_ACCEPT_DEVICE:-rxe0}
ETC=/etc/miracache
MARK=$ETC/.systemd-acceptance
UNITDIR=/etc/systemd/system
BINS=(mira-memnode mira-controller mirctl)
MNT=/mnt/mira-acc
t_start=$(date +%s)
since="@$t_start"
result=""
fails=0
passes=0
installed_bins=()
apt_installed=()

munit() { echo "mira-memnode-acc-$1"; }
CUNIT=mira-controller-acc

pass() { echo "PASS: $*"; passes=$((passes + 1)); }
check_fail() { echo "FAIL: $*"; fails=$((fails + 1)); }
fail() { result="FAIL: $*"; exit 1; }

teardown() {
  echo "== teardown"
  for u in "$CUNIT" $(for i in $(seq 1 $N); do munit "$i"; done); do
    if [[ -f $UNITDIR/$u.service ]] && grep -q '^# generated by tools/ci/systemd_acceptance.sh' "$UNITDIR/$u.service"; then
      systemctl disable --now "$u" >/dev/null 2>&1
      rm -f "$UNITDIR/$u.service"
      systemctl reset-failed "$u" >/dev/null 2>&1
    fi
  done
  systemctl daemon-reload
  for i in $(seq 1 $N); do
    mountpoint -q "$MNT-$i" && umount "$MNT-$i"
    rmdir "$MNT-$i" 2>/dev/null
    rm -rf "/var/lib/miracache-acc-$i"
  done
  rm -rf /var/lib/miracache-controller-acc
  [[ -f $MARK ]] && rm -rf "$ETC"
  for b in "${installed_bins[@]}"; do rm -f "/usr/local/bin/$b"; done
  rm -rf "$W"
  if [[ ${#apt_installed[@]} -gt 0 ]]; then
    DEBIAN_FRONTEND=noninteractive apt-get remove -y "${apt_installed[@]}" >/dev/null 2>&1 && echo "   removed packages ${apt_installed[*]}"
  fi
  left=""
  for u in "$CUNIT" $(for i in $(seq 1 $N); do munit "$i"; done); do
    [[ -e $UNITDIR/$u.service ]] && left+=" $u.service"; systemctl is-active -q "$u" 2>/dev/null && left+=" $u(active)"
  done
  for i in $(seq 1 $N); do mountpoint -q "$MNT-$i" && left+=" $MNT-$i"; [[ -e /var/lib/miracache-acc-$i ]] && left+=" /var/lib/miracache-acc-$i"; done
  [[ -f $MARK ]] && left+=" $ETC"
  for b in "${installed_bins[@]}"; do [[ -e /usr/local/bin/$b ]] && left+=" /usr/local/bin/$b"; done
  if [[ -n $left ]]; then echo "   teardown LEFT:$left"; [[ $result == OK:* || -z $result ]] && result="FAIL: teardown left$left"
  else echo "   teardown: units, configs, binaries, state dirs and mounts removed"; fi
  if [[ ${MIRA_ACCEPT_REMOVE_USER:-0} == 1 ]] && id mira >/dev/null 2>&1; then userdel mira && echo "   removed user mira"; fi
}
finish() {
  trap '' INT TERM   # a second signal must not cut the teardown short
  teardown
  if [[ -z $result ]]; then result="FAIL: aborted (see output above)"; fi
  echo "$result"
  [[ $result == OK:* ]]
}
trap finish EXIT
# INT/TERM (e.g. full_gate.sh killing its product step) exit through finish, so the teardown always runs.
trap 'trap "" INT TERM; result="FAIL: interrupted by TERM"; exit 143' TERM
trap 'trap "" INT TERM; result="FAIL: interrupted by INT"; exit 130' INT

[[ $(uname -s) == Linux ]] || fail "Linux host only"
[[ $(id -u) == 0 ]] || fail "run as root (installs units, users and mounts)"
[[ -d /run/systemd/system ]] || fail "systemd is not PID 1 here"
rdma link show 2>/dev/null | grep -q "^link $DEV/" || fail "no RDMA link $DEV (run tools/dev/rdma_setup.sh <netdev>)"
netdev=${RAIL_NETDEV:-eth0}
IP=$(ip -4 -o addr show "$netdev" | awk 'NR==1 {sub(/\/.*/, "", $4); print $4}')
HOST=$(hostname)
[[ -n $IP && -n $HOST ]] || fail "cannot read the address of $netdev or the hostname"
# Never take over something that is not ours.
if [[ -e $ETC && ! -f $MARK ]]; then result="FAIL: $ETC exists and was not made by this script: refusing"; trap - EXIT; echo "$result"; exit 1; fi
[[ -f $MARK ]] && echo "   leftover $ETC from an earlier acceptance run: replacing it"
for u in "$CUNIT" $(for i in $(seq 1 $N); do munit "$i"; done); do
  if [[ -f $UNITDIR/$u.service ]] && ! grep -q '^# generated by tools/ci/systemd_acceptance.sh' "$UNITDIR/$u.service"; then
    result="FAIL: $UNITDIR/$u.service exists and was not made by this script: refusing"; trap - EXIT; echo "$result"; exit 1
  fi
done
for b in "${BINS[@]}"; do
  if [[ -e /usr/local/bin/$b ]]; then result="FAIL: /usr/local/bin/$b already exists: refusing to overwrite it"; trap - EXIT; echo "$result"; exit 1; fi
done
echo "== host=$HOST $DEV on $netdev ip=$IP"

# ---- 1. build -------------------------------------------------------------------------------------------------------
if [[ ${MIRA_ACCEPT_SKIP_BUILD:-0} != 1 ]]; then
  echo "== build release (dev container)"
  mkdir -p "$ROOT/build"
  tools/dev/run.sh -- bash -c 'mkdir -p build/release/bin && cmake --preset release -DMIRACACHE_WERROR=ON >/dev/null &&
    cmake --build --preset release --target mira-memnode miracache_e2e_rdma_tests &&
    tools/dev/go.sh -C controller build -o "$PWD/build/release/bin/" ./cmd/mirctl ./cmd/mira-controller' \
    >"$ROOT/build/systemd-accept-build.log" 2>&1 || { tail -30 "$ROOT/build/systemd-accept-build.log"; fail "build"; }
fi
for f in "$B/server/mira-memnode" "$B/bin/mira-controller" "$B/bin/mirctl" "$B/tests/miracache_e2e_rdma_tests"; do
  [[ -x $f ]] || fail "missing $f (build first or unset MIRA_ACCEPT_SKIP_BUILD)"
done
# Runtime libraries of the memory node (the same set as deploy/docker/Dockerfile.memnode; runbook §3.1).
missing=$(ldd "$B/server/mira-memnode" | awk '/not found/ {print $1}' | tr '\n' ' ')
if [[ -n $missing ]]; then
  if [[ ${MIRA_ACCEPT_APT:-0} == 1 ]]; then
    want=(); for p in libibverbs1 librdmacm1t64 ibverbs-providers; do dpkg -s "$p" >/dev/null 2>&1 || want+=("$p"); done
    echo "== missing runtime libraries ($missing): apt-get install ${want[*]} (removed again at teardown)"
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "${want[@]}" >"$ROOT/build/systemd-accept-apt.log" 2>&1 \
      || fail "apt-get install ${want[*]}"
    apt_installed=("${want[@]}")
    missing=$(ldd "$B/server/mira-memnode" | awk '/not found/ {print $1}' | tr '\n' ' ')
  fi
  [[ -z $missing ]] || fail "mira-memnode needs $missing: apt-get install libibverbs1 librdmacm1t64 ibverbs-providers (or MIRA_ACCEPT_APT=1)"
fi

# ---- 2. user, PKI, install ------------------------------------------------------------------------------------------
echo "== mira user, PKI, install"
id mira >/dev/null 2>&1 || useradd --system --user-group --no-create-home --home-dir /var/lib/miracache --shell /usr/sbin/nologin mira \
  || fail "useradd mira"
MUID=$(id -u mira) MGID=$(id -g mira)
rm -rf "$W"; mkdir -p "$W" && chmod 700 "$W"
bash tools/dev/lab-certs.sh "$W/pki" --nodes 1,2,3,controller --clients 1 >/dev/null || fail "lab-certs"
OPS_ID="spiffe://lab/node-controller"   # the operator / controller identity (serverAuth + clientAuth cert)
install -m 0755 "$B/server/mira-memnode" /usr/local/bin/mira-memnode && installed_bins+=(mira-memnode)
install -m 0755 "$B/bin/mira-controller" /usr/local/bin/mira-controller && installed_bins+=(mira-controller)
install -m 0755 "$B/bin/mirctl" /usr/local/bin/mirctl && installed_bins+=(mirctl)
install -d -m 0755 "$ETC" && touch "$MARK"
install -d -m 0750 -o root -g mira "$ETC/pki"
install -m 0644 "$W/pki/ca.pem" "$ETC/pki/ca.pem"
for i in $(seq 1 $N); do
  install -m 0644 "$W/pki/node-$i.pem" "$ETC/pki/node-$i.pem"
  install -m 0600 -o mira -g mira "$W/pki/node-$i.key" "$ETC/pki/node-$i.key"
done
install -m 0644 "$W/pki/node-controller.pem" "$ETC/pki/controller.pem"
install -m 0600 -o mira -g mira "$W/pki/node-controller.key" "$ETC/pki/controller.key"

# Signing key (publish + security roles) and the trust file every node and the controller read.
/usr/local/bin/mirctl keys gen --out "$W/op.key" --roles publish,security >"$W/keygen.out" || fail "mirctl keys gen"
sed -n '/^\[\[key\]\]/,$p' "$W/keygen.out" >"$W/trust.toml"
grep -q '^public = ' "$W/trust.toml" || fail "no [[key]] block from mirctl keys gen"
install -m 0640 -o root -g mira "$W/trust.toml" "$ETC/trust.toml"
install -m 0600 -o mira -g mira "$W/op.key" "$ETC/publish.seed"
install -m 0600 -o mira -g mira "$W/op.key" "$ETC/security.seed"

# Per-node store: tmpfs owned by mira (file backing; hugetlbfs needs 1 GiB pages reserved at boot, runbook §3.2).
for i in $(seq 1 $N); do
  mkdir -p "$MNT-$i"
  mountpoint -q "$MNT-$i" || mount -t tmpfs -o "size=64m,uid=$MUID,gid=$MGID,mode=0700" "mira-acc-$i" "$MNT-$i" || fail "mount $MNT-$i"
  cat >"$W/memnode-$i.toml" <<EOF
# generated by tools/ci/systemd_acceptance.sh (bundle mode: no [lab], no class-A keys; see the bundle-mode notes in the operations guide)
[node]
device = "$DEV"
listen = ["$IP:$((RAIL0 + i))"]
state_dir = "/var/lib/miracache-acc-$i"
drain_ms = 3000
[store]
backing = "file"
dir = "$MNT-$i"
segment_bytes = 4194304
run_bytes = 262144
min_block_bytes = 4096
n_segments = 4
[control]
trust_keys = "$ETC/trust.toml"
[admin]
listen = "127.0.0.1:$((ADMIN0 + i))"
cert = "$ETC/pki/node-$i.pem"
key = "$ETC/pki/node-$i.key"
ca = "$ETC/pki/ca.pem"
[telemetry]
listen = "127.0.0.1:$((TEL0 + i))"
EOF
  install -m 0640 -o root -g mira "$W/memnode-$i.toml" "$ETC/memnode-$i.toml"
  # Unit from the shipped file: only the instance name, StateDirectory and --config differ.
  { echo "# generated by tools/ci/systemd_acceptance.sh from deploy/systemd/mira-memnode.service (instance $i)"
    sed -e "s|^Description=miracache memory node|& $i (acceptance)|" \
        -e "s|^StateDirectory=miracache$|StateDirectory=miracache-acc-$i|" \
        -e "s|^ExecStart=/usr/local/bin/mira-memnode --config /etc/miracache/memnode.toml$|ExecStart=/usr/local/bin/mira-memnode --config $ETC/memnode-$i.toml|" \
        deploy/systemd/mira-memnode.service; } >"$UNITDIR/$(munit "$i").service"
  grep -q "^StateDirectory=miracache-acc-$i$" "$UNITDIR/$(munit "$i").service" && grep -q "^ExecStart=.*memnode-$i.toml$" "$UNITDIR/$(munit "$i").service" \
    || fail "unit generation: the shipped mira-memnode.service changed shape"
done
{ echo "# generated by tools/ci/systemd_acceptance.sh from deploy/systemd/mira-controller.service"
  sed -e "s|^Description=miracache controller|& (acceptance)|" \
      -e "s|^StateDirectory=miracache-controller$|StateDirectory=miracache-controller-acc|" \
      -e "s|/var/lib/miracache-controller/|/var/lib/miracache-controller-acc/|g" \
      -e "s|--api-listen :9470|--api-listen 127.0.0.1:$CTL_PORT|" \
      deploy/systemd/mira-controller.service; } >"$UNITDIR/$CUNIT.service"
grep -q "^StateDirectory=miracache-controller-acc$" "$UNITDIR/$CUNIT.service" && grep -q -- "--api-listen 127.0.0.1:$CTL_PORT" "$UNITDIR/$CUNIT.service" \
  || fail "unit generation: the shipped mira-controller.service changed shape"
systemctl daemon-reload

# ---- helpers --------------------------------------------------------------------------------------------------------
jctl() { journalctl -u "$1" --since "$since" -o cat --no-pager 2>/dev/null; }
wait_log() {  # wait_log <unit> <grep -E pattern> [after-count]: wait until the journal has more than <after-count> matches
  local after=${3:-0}
  for _ in $(seq 1 120); do
    [[ $(jctl "$1" | grep -cE "$2") -gt $after ]] && return 0
    systemctl is-active -q "$1" || { jctl "$1" | tail -15; return 1; }
    sleep 0.5
  done
  jctl "$1" | tail -15
  return 1
}
node_id() { curl -s "http://127.0.0.1:$((TEL0 + $1))/metrics" | sed -n 's/^miracache_node_info{node_id="\([0-9]*\)".*/\1/p' | head -n1; }
mainpid() { systemctl show -p MainPID --value "$1"; }
node_warns() { for i in $(seq 1 $N); do jctl "$(munit "$i")" | grep -E 'level=(warn|error)' | tail -n3 | sed "s/^/   node $i: /"; done; }
ctl_curl() { curl -s --cert "$W/pki/node-controller.pem" --key "$W/pki/node-controller.key" --cacert "$W/pki/ca.pem" "https://127.0.0.1:$CTL_PORT$1"; }
admins=$(for i in $(seq 1 $N); do printf '127.0.0.1:%d,' $((ADMIN0 + i)); done); admins=${admins%,}
mtls=(--cert "$W/pki/node-controller.pem" --tls-key "$W/pki/node-controller.key" --ca "$W/pki/ca.pem")
client() {  # client <log> [env...]: the e2e client (tests/e2e/multi_node_rdma_test.cpp, ExternalNodes) from the dev container
  local log=$1; shift
  tools/dev/run.sh --rdma -- env "$@" MIRA_EXT_DEVICE="$DEV" MIRA_EXT_IP="$IP" MIRA_EXT_RAILS="$((RAIL0 + 1)),$((RAIL0 + 2)),$((RAIL0 + 3))" \
    MIRA_EXT_ADMIN="$((ADMIN0 + 1)),$((ADMIN0 + 2)),$((ADMIN0 + 3))" MIRA_EXT_PKI=/work/build/systemd-accept/pki \
    MIRA_EXT_TRUST=/work/build/systemd-accept/trust.toml MIRA_EXT_CLIENT_STATE=/work/build/systemd-accept/clientstate \
    MIRA_EXT_CONTROLLER="127.0.0.1:$CTL_PORT" \
    build/release/tests/miracache_e2e_rdma_tests --gtest_filter='ExternalNodes.*' >"$log" 2>&1
}

# ---- 3. start: nodes, first publish, controller --------------------------------------------------------------------
echo "== start $N memory nodes (bundle mode)"
for i in $(seq 1 $N); do systemctl enable --now "$(munit "$i")" >/dev/null 2>&1 || fail "start $(munit "$i")"; done
for i in $(seq 1 $N); do wait_log "$(munit "$i")" 'msg="admin \(mTLS\) on"' || fail "node $i: no 'admin (mTLS) on'"; done

cat >"$W/cluster.toml" <<EOF
reason = "systemd acceptance"
$(for i in $(seq 1 $N); do printf '[[nodes]]\nadmin = "127.0.0.1:%d"\nweight = 1\n' $((ADMIN0 + i)); done)
[[principals]]
name = "lab"
identities = ["spiffe://lab/client-1"]
quota_bytes = 16777216
max_scopes = 1000
[[rbac]]
identity = "$OPS_ID"
roles = ["operator", "security-admin"]
[config.cluster.memnode.store]
max_bytes = 16777216
max_scopes = 1000
[config.cluster.placement]
replicas = 1
EOF
echo "== first publish (mirctl)"
/usr/local/bin/mirctl bundle publish --source "$W/cluster.toml" --key "$W/op.key" --sec-key "$W/op.key" --trust "$W/trust.toml" "${mtls[@]}" \
  >"$W/publish.out" 2>&1 || { cat "$W/publish.out"; fail "mirctl bundle publish"; }
tail -n2 "$W/publish.out" | sed 's/^/   /'
for i in $(seq 1 $N); do wait_log "$(munit "$i")" 'msg="listening"' || fail "node $i: no 'listening'"; done

echo "== controller hand-over (--recover-from, as mira) and unit"
systemd-run --quiet --wait --collect --pipe -p User=mira -p Group=mira -p StateDirectory=miracache-controller-acc -p StateDirectoryMode=0700 \
  -p UMask=0077 /usr/local/bin/mira-controller --recover-from "127.0.0.1:$((ADMIN0 + 1))" --store-dir /var/lib/miracache-controller-acc/store \
  --trust-keys "$ETC/trust.toml" --publish-key "$ETC/publish.seed" --security-key "$ETC/security.seed" \
  --cert "$ETC/pki/controller.pem" --key "$ETC/pki/controller.key" --ca "$ETC/pki/ca.pem" >"$W/recover.out" 2>&1 \
  || { cat "$W/recover.out"; fail "mira-controller --recover-from"; }
systemctl enable --now "$CUNIT" >/dev/null 2>&1 || fail "start $CUNIT"

# ---- 4. checks ------------------------------------------------------------------------------------------------------
echo "== checks"
sleep 2   # let the controller's first reconcile round settle (not a correctness wait: checks below poll or retry)
all_units=("$CUNIT"); for i in $(seq 1 $N); do all_units+=("$(munit "$i")"); done
bad=""; for u in "${all_units[@]}"; do systemctl is-active -q "$u" || bad+=" $u"; done
[[ -z $bad ]] && pass "units active: ${all_units[*]}" || check_fail "units not active:$bad"

bad=""
for i in $(seq 1 $N); do
  jctl "$(munit "$i")" | grep -q 'msg="admin (mTLS) on"' || bad+=" node$i:admin"
  jctl "$(munit "$i")" | grep -q 'msg="listening"' || bad+=" node$i:listening"
done
[[ -z $bad ]] && pass "journal: admin (mTLS) on + listening on all $N nodes" || check_fail "journal lines missing:$bad"

# User and capabilities. CAP_IPC_LOCK = bit 14 = 0x4000.
for u in "${all_units[@]}"; do
  pid=$(mainpid "$u")
  [[ -n $pid && $pid != 0 ]] || { check_fail "$u: no MainPID"; continue; }
  uid=$(awk '/^Uid:/ {print $2}' "/proc/$pid/status")
  eff=$(awk '/^CapEff:/ {print $2}' "/proc/$pid/status"); amb=$(awk '/^CapAmb:/ {print $2}' "/proc/$pid/status")
  bnd=$(awk '/^CapBnd:/ {print $2}' "/proc/$pid/status")
  if [[ $u == "$CUNIT" ]]; then want=0000000000000000 wamb=0000000000000000; else want=0000000000004000 wamb=0000000000004000; fi
  if [[ $uid == "$MUID" && $eff == "$want" && $amb == "$wamb" && $bnd == "$want" ]]; then
    pass "$u runs as mira (uid $uid), CapEff=$eff CapAmb=$amb CapBnd=$bnd"
  else
    check_fail "$u uid=$uid (mira=$MUID) CapEff=$eff CapAmb=$amb CapBnd=$bnd (want $want / $wamb / $want)"
  fi
  [[ $u == "$CUNIT" ]] || { grep -q '^Max locked memory *unlimited' "/proc/$pid/limits" && pass "$u memlock unlimited" || check_fail "$u memlock not unlimited"; }
done

declare -a ID
for i in $(seq 1 $N); do ID[$i]=$(node_id "$i"); done
if [[ -n ${ID[1]} && -n ${ID[2]} && -n ${ID[3]} && ${ID[1]} != "${ID[2]}" && ${ID[2]} != "${ID[3]}" && ${ID[1]} != "${ID[3]}" ]]; then
  pass "computed node ids ${ID[1]} ${ID[2]} ${ID[3]} (none in config); persisted: $(for i in $(seq 1 $N); do tr -d '\n' <"/var/lib/miracache-acc-$i/node-id" 2>/dev/null; printf ' '; done)"
else
  check_fail "node ids missing or duplicate: '${ID[1]}' '${ID[2]}' '${ID[3]}'"
fi

# Spec §1.1 goal 10: every log line of a memory node, once its identity is known, carries node_id + host + addr (IP).
# Lines before the identity is loaded (process start) can only carry host=; they are counted, not failed.
log_check() {  # log_check <i>
  journalctl -u "$(munit "$1")" --since "$since" -o short --no-pager 2>/dev/null | grep ' ts=' |
    awk -v id="${ID[$1]}" -v host="$HOST" -v addr="$IP:$((RAIL0 + $1))" '
      { pid = $5; sub(/.*\[/, "", pid); sub(/\].*/, "", pid); n++ }
      / node_id=/ { seen[pid] = 1
        if (index($0, " node_id=" id " ") == 0 || index($0, " host=" host " ") == 0 || index($0, " addr=" addr " ") == 0) { bad++; if (!sample) sample = $0 }
        next }
      { if (seen[pid]) { bad++; if (!sample) sample = $0 } else pre++
        if (index($0, " host=" host " ") == 0) { bad++; if (!sample) sample = $0 } }
      END { printf "%d %d %d %s\n", n, pre + 0, bad + 0, sample }'
}
logs_ok() {
  local ok=1
  for i in $(seq 1 $N); do
    read -r n pre badn sample <<<"$(log_check "$i")"
    if [[ $badn == 0 && $n -gt 0 ]]; then echo "   node $i: $n lines, $pre before the identity, all others node_id=${ID[$i]} host=$HOST addr=$IP:$((RAIL0 + i))"
    else echo "   node $i: $badn of $n lines lack node_id/host/addr, e.g. $sample"; ok=0; fi
  done
  [[ $ok == 1 ]]
}
logs_ok && pass "log lines carry node ID + hostname + IP" || check_fail "log lines without node ID + hostname + IP"
echo "   sample: $(jctl "$(munit 1)" | grep 'msg="listening"' | head -n1)"

st=$(ctl_curl /v1/status)
nn=$(grep -o '"admin":"[^"]*"' <<<"$st" | sort -u | wc -l)
na=$(grep -o '"state":"active"' <<<"$st" | wc -l)
[[ $nn == "$N" && $na == "$N" ]] && pass "controller sees $N active nodes (/v1/status)" || check_fail "controller /v1/status: $nn nodes, $na active: ${st:0:300}"
/usr/local/bin/mirctl bundle status --nodes "$admins" "${mtls[@]}" >"$W/bstatus.out" 2>&1 \
