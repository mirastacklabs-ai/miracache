if [[ $rc -eq 0 && $ext == *"oracle=ok"* ]]; then pass "client store/lookup/fetch byte-for-byte: $ext"
else tail -20 "$W/client1.log"; node_warns; check_fail "client e2e (rc=$rc) $ext"; fi

echo "== systemctl stop / start node 3"
u3=$(munit 3)
t0=$(date +%s.%N); systemctl stop "$u3"; t1=$(date +%s.%N)
code=$(systemctl show -p ExecMainStatus --value "$u3"); res=$(systemctl show -p Result --value "$u3")
stop_s=$(awk -v a="$t0" -v b="$t1" 'BEGIN {printf "%.1f", b - a}')
drain=$(jctl "$u3" | grep -E 'GOAWAY sent|drain complete|drain deadline|stopped' | sed 's/.*msg=//' | tr '\n' ';')
if [[ ($code == 0 || $code == 3) && $res == success ]] && awk -v s="$stop_s" 'BEGIN {exit !(s < 30)}'; then
  pass "clean stop: exit $code, Result=$res in ${stop_s}s (TimeoutStopSec=30); $drain"
else check_fail "stop: exit $code Result=$res in ${stop_s}s; $drain"; fi
nl=$(jctl "$u3" | grep -c 'msg="listening"')
systemctl start "$u3" && wait_log "$u3" 'msg="listening"' "$nl" || check_fail "node 3 did not come back to 'listening'"
id3=$(node_id 3)
if [[ -n $id3 && $id3 == "${ID[3]}" ]] && ! jctl "$u3" | grep -q 'node replaced'; then pass "node 3 restarted with the same persisted id $id3"
else check_fail "node 3 id ${ID[3]} -> '$id3' (or logged 'node replaced')"; fi

echo "== client traffic loop while 'systemctl restart' node 2"
client "$W/client2.log" MIRA_EXT_LOOP_S=25 MIRA_EXT_SCOPE_SET=1 &
cpid=$!
for _ in $(seq 1 240); do grep -q '^\[EXT-LOOP\] start' "$W/client2.log" 2>/dev/null && break; kill -0 "$cpid" 2>/dev/null || break; sleep 0.5; done
sleep 4
u2=$(munit 2); nl=$(jctl "$u2" | grep -c 'msg="listening"')
t0=$(date +%s.%N)
if systemctl restart "$u2" && wait_log "$u2" 'msg="listening"' "$nl"; then
  t1=$(date +%s.%N)
  drain=$(jctl "$u2" | grep -E 'GOAWAY sent|drain complete|drain deadline' | tail -n2 | sed 's/.*msg=//' | tr '\n' ';')
  if jctl "$u2" | grep -q 'Failed with result'; then check_fail "node 2 restart: systemd logged 'Failed with result'"
  else pass "systemctl restart node 2 under traffic: back to 'listening' in $(awk -v a="$t0" -v b="$t1" 'BEGIN {printf "%.1f", b - a}')s, no failed result; $drain"; fi
else check_fail "node 2 did not come back after restart"; fi
wait "$cpid"; rc=$?
loop=$(grep '^\[EXT-LOOP\] rounds' "$W/client2.log" | tail -n1)
if [[ $rc -eq 0 && $loop == *"corrupt=0 "* && $loop == *"recovered=yes"* ]]; then pass "client kept working through the restart (misses, no errors): $loop"
else tail -20 "$W/client2.log"; node_warns; check_fail "client during restart (rc=$rc): $loop"; fi
id2=$(node_id 2)
[[ $id2 == "${ID[2]}" ]] && pass "node 2 kept id $id2 across restart" || check_fail "node 2 id ${ID[2]} -> '$id2'"

st=$(ctl_curl /v1/status)
nn=$(grep -o '"admin":"[^"]*"' <<<"$st" | sort -u | wc -l); na=$(grep -o '"state":"active"' <<<"$st" | wc -l)
[[ $nn == "$N" && $na == "$N" ]] && pass "controller still sees $N active nodes after the restarts" || check_fail "controller after restarts: $nn nodes, $na active"
bad=""; for u in "${all_units[@]}"; do systemctl is-active -q "$u" || bad+=" $u"; done
[[ -z $bad ]] && pass "all units active at the end" || check_fail "units not active at the end:$bad"
logs_ok >/dev/null && pass "log lines (after restarts) carry node ID + hostname + IP" || { logs_ok; check_fail "log lines after restarts"; }

