const goldenDir = "../../proto/golden/bundle_v1"

func publishSeedHex() string  { return hex.EncodeToString(seedFrom(0x01)) }
func securitySeedHex() string { return hex.EncodeToString(seedFrom(0x21)) }

// goldenTrustFile is the trust file the golden envelope verifies against (publish-only and
// security-only keys, as in the role-binding tests).
func goldenTrustFile() string {
	return "# Trust file for proto/golden/bundle_v1/go_emitted.envelope (test seeds, never production keys).\n" +
		"[[key]]\npublic = \"" + hex.EncodeToString(pubOf(publishKey)) + "\"\nroles = [\"publish\"]\n\n" +
		"[[key]]\npublic = \"" + hex.EncodeToString(pubOf(securityKey)) + "\"\nroles = [\"security\"]\n"
}

func goldenExpect(e *Envelope, raw []byte) string {
	b := goldenBody()
	s := goldenSec()
	lines := []string{
		"# Go-emitted bundle (MB1). Key=value, one per line; hashes are SHA-256, 64 lower-case hex.",
		"publish_seed=" + publishSeedHex(),
		"security_seed=" + securitySeedHex(),
		"publish_public=" + hex.EncodeToString(pubOf(publishKey)),
		"security_public=" + hex.EncodeToString(pubOf(securityKey)),
		"key_id=" + e.KeyID,
		"sec_key_id=" + e.SecKeyID,
		"generation=" + strconv.FormatUint(b.Generation, 10),
		"sec_generation=" + strconv.FormatUint(s.SecGeneration, 10),
		"epoch=" + strconv.FormatUint(b.Membership.Epoch, 10),
		"sec_len=" + strconv.Itoa(len(e.Sec)),
		"body_len=" + strconv.Itoa(len(e.Body)),
		"sec_hash=" + HashHex(e.Sec),
		"body_hash=" + HashHex(e.Body),
		"envelope_sha256=" + HashHex(raw),
		"sig=" + hex.EncodeToString(e.Sig),
		"sec_sig=" + hex.EncodeToString(e.SecSig),
		"principal_id_prod-llama=" + strconv.FormatUint(uint64(PrincipalID("prod-llama")), 10),
		"principal_id_staging=" + strconv.FormatUint(uint64(PrincipalID("staging")), 10),
	}
	return strings.Join(lines, "\n") + "\n"
}

func readGolden(t *testing.T, name string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(goldenDir, name))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// TestGoEmittedGolden regenerates the committed Go-emitted envelope and requires it byte-equal
// (signatures are deterministic). MB1_WRITE_GOLDEN=1 rewrites the files.
func TestGoEmittedGolden(t *testing.T) {
	e, raw := goldenEnvelope(t)
	files := map[string][]byte{
		"go_emitted.envelope":   raw,
		"go_emitted.expect":     []byte(goldenExpect(e, raw)),
		"go_emitted.trust.toml": []byte(goldenTrustFile()),
	}
	if os.Getenv("MB1_WRITE_GOLDEN") == "1" {
		for n, c := range files {
			if err := os.WriteFile(filepath.Join(goldenDir, n), c, 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	for n, c := range files {
		if got := readGolden(t, n); !bytes.Equal(got, c) {
			t.Errorf("%s differs from the regenerated bytes (MB1_WRITE_GOLDEN=1 rewrites it)", n)
		}
	}
	// The committed trust file and envelope verify and parse on their own.
	tr, err := ParseTrustFile(readGolden(t, "go_emitted.trust.toml"))
	if err != nil {
		t.Fatal(err)
	}
	b, err := Open(tr, readGolden(t, "go_emitted.envelope"))
	if err != nil {
		t.Fatal(err)
	}
	if b.Body.Generation != 42 || b.Sec.SecGeneration != 5 {
		t.Fatal("golden content")
	}
}

// TestMB2Goldens verifies every MB2-generated envelope in proto/golden/bundle_v1 with MB2's
// trust file (trust.toml if present, else the Go trust file). Files named valid*.envelope must
// verify and parse; reject*.envelope must be rejected with the reason and detail of its .reject file. Fails (never skips) below the reject-file floor.
func TestMB2Goldens(t *testing.T) {
	all, _ := filepath.Glob(filepath.Join(goldenDir, "*.envelope"))
	var mb2 []string
	for _, p := range all {
		if !strings.HasPrefix(filepath.Base(p), "go_emitted") {
			mb2 = append(mb2, p)
		}
	}
	// A wrong path or a deleted file must fail, never pass: the corpus has at least this many reject files (the C++ suite
	// has the same floor) and the two valid ones.
	const rejectFloor = 40
	rejects := 0
	for _, p := range mb2 {
		if strings.HasPrefix(filepath.Base(p), "reject") {
			rejects++
		}
	}
	if rejects < rejectFloor {
		t.Fatalf("found %d reject*.envelope files in %s, want at least %d", rejects, goldenDir, rejectFloor)
	}
	trustPath := filepath.Join(goldenDir, "trust.toml")
	if _, err := os.Stat(trustPath); err != nil {
		trustPath = filepath.Join(goldenDir, "go_emitted.trust.toml")
	}
	tr, err := LoadTrustFile(trustPath)
	if err != nil {
		t.Fatalf("trust file %s: %v", trustPath, err)
	}
	for _, p := range mb2 {
		name := filepath.Base(p)
		raw, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		switch {
		case strings.HasPrefix(name, "valid"):
			b, err := Open(tr, raw)
			if err != nil {
				t.Errorf("%s: %v", name, err)
				continue
			}
			checkMB2Expect(t, name, b)
		case strings.HasPrefix(name, "reject"):
			b, err := Open(tr, raw)
			if err == nil {
				// The wall-clock rule runs after a successful open (fixed "now", as the C++ suite does).
				err = CheckDropBeforeNotFuture(b.Sec, time.Date(2026, 11, 12, 0, 0, 0, 0, time.UTC), 0)
			}
			if err == nil {
				t.Errorf("%s: accepted, want reject", name)
			} else {
				checkRejectExpect(t, name, err)
			}
		default:
			t.Logf("%s: not named valid*/reject*, not checked", name)
		}
	}
}

// checkRejectExpect compares a refusal against the shared reject_*.reject file next to the envelope ("reason: <class>"
// , "go:" and "cpp:" lines: the exact message fragment of each side); the C++ suite reads the same file. A missing file is a failure.
func checkRejectExpect(t *testing.T, name string, err error) {
	t.Helper()
	txt, rerr := os.ReadFile(filepath.Join(goldenDir, strings.TrimSuffix(name, ".envelope")+".reject"))
	if rerr != nil {
		t.Errorf("%s: no shared .reject expectation: %v", name, rerr)
		return
	}
	var reason, detail string
	for _, line := range strings.Split(string(txt), "\n") {
		if v, ok := strings.CutPrefix(line, "reason: "); ok {
			reason = v
		} else if v, ok := strings.CutPrefix(line, "go: "); ok {
			detail = v
		}
	}
	if reason == "" || detail == "" {
		t.Errorf("%s.reject needs a reason and a go line", name)
		return
	}
	if got := ReasonOf(err); got != reason {
		t.Errorf("%s: reason %q, want %q (%v)", name, got, reason, err)
	}
	if !strings.Contains(err.Error(), detail) {
		t.Errorf("%s: message %q does not contain %q", name, err.Error(), detail)
	}
}

// checkMB2Expect compares the fields of a "name: value" .expect file that Go can recompute.
func checkMB2Expect(t *testing.T, name string, b *Bundle) {
	t.Helper()
	txt, err := os.ReadFile(filepath.Join(goldenDir, strings.TrimSuffix(name, ".envelope")+".expect"))
	if err != nil {
		return
	}
	e := b.Envelope
	want := map[string]string{
		"key_id": e.KeyID, "sec_key_id": e.SecKeyID,
		"sig": hex.EncodeToString(e.Sig), "sec_sig": hex.EncodeToString(e.SecSig),
		"sec_len":        strconv.Itoa(len(e.Sec)),
		"generation":     strconv.FormatUint(b.Body.Generation, 10),
		"sec_generation": strconv.FormatUint(b.Sec.SecGeneration, 10),
		"epoch":          strconv.FormatUint(b.Body.Membership.Epoch, 10),
		"body_sha256":    b.ContentHash, "sec_sha256": b.SecHash,
	}
	for _, l := range strings.Split(string(txt), "\n") {
		k, v, ok := strings.Cut(l, ": ")
		if !ok {
			continue
		}
		if w, known := want[k]; known && w != v {
			t.Errorf("%s: %s = %s, expect file says %s", name, k, w, v)
		}
	}
}
